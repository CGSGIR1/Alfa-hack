def make_tags(row):
    tags = []
    if row["CL_PRODUCT_LOA_MARK"] == 1 or row["CL_PRODUCT_LEA_MARK"] == 1:
        tags.append("ставка")
    if row["CL_PRODUCT_DEP_MARK"] == 1:
        tags.append("ставка")
    if row["CL_PRODUCT_ZPP_MARK"] == 1:
        tags.append("рынок_труда")
    if row["CL_PRODUCT_GAR_MARK"] == 1:
        tags.append("госзаказ")
    tags += industry_tags.get(row["industry"], [])
    tags += subindustry_tags.get(row["subindustry"], [])
    if pd.notnull(row["FTS_COUNTRY_NAME"]):
        tags += ["валюта", "санкции"]
        if "КИТАЙ" in row["FTS_COUNTRY_NAME"]:
            tags.append("юань")
    return sorted(set(tags))
