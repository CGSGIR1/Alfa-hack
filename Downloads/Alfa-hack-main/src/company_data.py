WEAK_TAGS = {"спрос", "рынок_труда"}
def score(company, item):
    matched = set(company["TAGS"]) & set(item["tags"])
    strong = matched - WEAK_TAGS
    weak = matched & WEAK_TAGS
    points = 0
    reasons = []
    if strong:
        points += 0.5
        reasons.append("совпали теги: " + ", ".join(sorted(strong)))
    elif weak:
        points += 0.2
        reasons.append("совпал только общий тег: " + ", ".join(sorted(weak)))
    if company["industry"] in item["okved"]:
        points += 0.3
        reasons.append("новость про вашу отрасль")
    return points, reasons
