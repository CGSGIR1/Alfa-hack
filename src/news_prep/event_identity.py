"""Extra fields for the existing news-preparation call, not a pairwise LLM call."""
from copy import deepcopy

VERSION='news-event-identity-1.0'
INSTRUCTIONS='''
ДОПОЛНЕНИЕ: ИДЕНТИФИКАЦИЯ ГЛАВНОГО СОБЫТИЯ
Добавь на верхнем уровне ответа поле event_identity по схеме ниже. Оно нужно для
сопоставления публикаций одного события. Сходная тема или общий справочный абзац
не означают одинаковое событие. Выделяй событие всей статьи, а не наиболее похожий фон.

- main_thesis: один главный факт с предметом, действием и существенными условиями.
- event_type: single_event, digest (несколько самостоятельных событий) или unclear.
- actors: только участники главного события, названия из исходного текста.
  «Регулятор», «компания», «он» — обозначения уже названного участника, не отдельные actors.
- action: конкретное действие; object: конкретный предмет, инструмент, выпуск, документ
  или показатель. Сохраняй название компании, валютную пару, годы бюджета, номер выпуска,
  если они указаны. Не обобщай до "финансы", "экономика", "рынок".
- stage: proposed, planned, announced, adopted, effective, completed, reported или unknown.
  План размещения и завершение размещения — разные стадии. Новое подтверждение участника
  и прежнее сообщение из отчётности тоже могут содержать новые сведения.
- event_date: YYYY-MM-DD только при явной дате в источнике, иначе null.
  date_role: effective (дата действия курса или решения), occurred, publication,
  reporting_period или unknown. Дата публикации автоматически не заменяет дату события.
- period: период события дословно из текста или null.
- metrics: существенные показатели именно главного события. Каждый объект:
  name, value (строка с точным числом, точка как разделитель), unit, period (или null),
  source_block_id и source_quote. Сохраняй единицы, период, валюту, направление изменения;
  не добавляй прогнозы и исторические числа из справочного контекста. Не считай отсутствие
  числа равным нулю; не заменяй точное значение округлением из заголовка.
- main_source_block_ids: блоки главного события. source_evidence: точные содержательные
  цитаты из этих блоков, минимум 40 символов и 6 слов. Каждый объект: block_id, quote.
- limitations: что о событии не установлено. Не выдумывай участников, даты и идентификаторы.
  При противоречии дат или значений перечисли противоречие, оставь спорное поле null.
  Не исправляй месяц или год по смыслу заголовка и не подставляй дату публикации.

Для обзора нескольких событий установи event_type=digest: сравнение одного тезиса не
должно приводить к отбрасыванию всего обзора. Это поле не меняет разбиение статьи,
цитаты фрагментов и два текста для эмбеддинга.

Формат добавляемого поля:
"event_identity": {
 "schema_version":"news-event-identity-1.0", "main_thesis":"...",
 "event_type":"single_event|digest|unclear", "actors":["..."],
 "action":"...", "object":"...", "stage":"reported",
 "event_date":null, "date_role":"unknown", "period":null,
 "metrics":[{"name":"...","value":"81.97","unit":"рублей за доллар США",
             "period":null,"source_block_id":"B001","source_quote":"точная цитата"}],
 "main_source_block_ids":["B001"],
 "source_evidence":[{"block_id":"B001","quote":"точная содержательная цитата"}],
 "limitations":[]
}
Статус пригодности и решение об объединении определяет приложение. Не утверждай,
что публикация является дубликатом: другую публикацию ты сейчас не видишь.
'''


def prepared(raw):
    """Retain the model metadata; the importer validates original evidence."""
    if not isinstance(raw,dict):
        return dict(schema_version=VERSION,status='missing',limitations=['Event identity was not supplied'])
    return deepcopy(raw)
