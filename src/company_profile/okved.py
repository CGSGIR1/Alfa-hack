def normalize_code(code: str) -> str:
    """Возвращает ноль, потерянный при выгрузке: '41.2' -> '41.20', '68.1' -> '68.10'.

    В данных одно и то же название ОКВЭД встречается с кодами '41.20' и '41.2',
    то есть второй уровень кода всегда двузначный.
    """
    code = str(code).strip()
    parts = code.split(".")
    parts[0] = parts[0].zfill(2)
    if len(parts) > 1 and len(parts[1]) == 1:
        parts[1] += "0"
    return ".".join(parts)


def okved_class(code: str) -> str:
    """Класс ОКВЭД (два уровня), по нему сравниваем компании одной отрасли: '41.20.9' -> '41.20'."""
    return ".".join(code.split(".")[:2])


def division_name(division: str) -> str:
    return DIVISIONS.get(division, f"раздел ОКВЭД {division}")
