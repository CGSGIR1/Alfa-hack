# Теги, которые совпадают почти у всех и сами по себе слабо говорят о релевантности.
WEAK_TAGS = {"спрос", "рынок_труда"}

# Доля платежей контрагентов одной отрасли, начиная с которой их теги
# передаются компании как косвенная чувствительность.
COUNTERPARTY_TAG_MIN_SHARE = 0.10


def okved_parts(code: str) -> tuple[str, str]:
    """'46.51.2' -> ('46', '46.51'); '41.2' -> ('41', '41.2')."""
    parts = code.split(".")
    return parts[0].zfill(2), ".".join(parts[:2])


def make_tags(row: dict, counterparty_mix: list[dict] | None = None) -> dict[str, list[dict]]:
    """Теги компании с причинами: {тег: [{"source", "reason"}, ...]}.

    source — откуда тег: product (продукты банка), okved (своя отрасль),
    fts (ВЭД), counterparty (отрасли контрагентов, косвенное влияние).
    Ранжирование может взвешивать прямые и косвенные теги по-разному.

    counterparty_mix — доли отраслей поставщиков и покупателей
    ({"role", "division", "name", "share"}), из них берутся косвенные теги.
    """
    tags: dict[str, list[dict]] = {}

    def add(tag: str, source: str, reason: str) -> None:
        reasons = tags.setdefault(tag, [])
        if all(r["reason"] != reason for r in reasons):
            reasons.append({"source": source, "reason": reason})

    if row["CL_PRODUCT_LOA_MARK"] == 1:
        add("ставка", "product", "CL_PRODUCT_LOA_MARK=1 (кредиты)")
    if row["CL_PRODUCT_LEA_MARK"] == 1:
        add("ставка", "product", "CL_PRODUCT_LEA_MARK=1 (лизинг)")
    if row["CL_PRODUCT_DEP_MARK"] == 1:
        add("ставка", "product", "CL_PRODUCT_DEP_MARK=1 (депозиты)")
    if row["CL_PRODUCT_ZPP_MARK"] == 1:
        add("рынок_труда", "product", "CL_PRODUCT_ZPP_MARK=1 (зарплатный проект)")
    if row["CL_PRODUCT_GAR_MARK"] == 1:
        add("госзаказ", "product", "CL_PRODUCT_GAR_MARK=1 (банковские гарантии)")

    division, group = okved_parts(row["MAINOKVED_CODE"])
    for tag in industry_tags.get(division, []):
        add(tag, "okved", f"ОКВЭД {division} (основной вид деятельности)")
    for tag in subindustry_tags.get(group, []):
        add(tag, "okved", f"ОКВЭД {group} (основной вид деятельности)")

    countries = row.get("countries") or []
    if countries:
        reason = "ВЭД по данным ФТС: " + ", ".join(countries)
        add("валюта", "fts", reason)
        add("санкции", "fts", reason)
        if "КИТАЙ" in countries:
            add("юань", "fts", reason)

    for tag, reasons in counterparty_tags(counterparty_mix or []).items():
        for r in reasons:
            add(tag, r["source"], r["reason"])

    return dict(sorted(tags.items()))


def counterparty_tags(counterparty_mix: list[dict]) -> dict[str, list[dict]]:
    """Косвенные теги из отраслей контрагентов с заметной долей платежей."""
    tags: dict[str, list[dict]] = {}
    for item in counterparty_mix:
        if item["share"] < COUNTERPARTY_TAG_MIN_SHARE:
            continue
        who = "поставщики" if item["role"] == "supplier" else "покупатели"
        reason = f"{who}: {item['name']} ({item['share']:.0%} платежей)"
        for tag in industry_tags.get(item["division"], []):
            if tag not in WEAK_TAGS:
                tags.setdefault(tag, []).append({"source": "counterparty", "reason": reason})
    return tags


def rate_exposure(row: dict) -> str | None:
    """Знак влияния роста ставки: заёмщику во вред, держателю депозитов на пользу."""
    borrower = row["CL_PRODUCT_LOA_MARK"] == 1 or row["CL_PRODUCT_LEA_MARK"] == 1
    depositor = row["CL_PRODUCT_DEP_MARK"] == 1
    if borrower and depositor:
        return "mixed"
    if borrower:
        return "borrower"
    if depositor:
        return "depositor"
    return None
